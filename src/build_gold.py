def _load_silver_data() -> pd.DataFrame:
    """
    Step 1 — Read all records from the Silver layer table.
    The Silver table holds clean, typed, deduplicated clinical trial data.
    """
    logger.info("Step 1: Loading Silver layer data from 'silver_clinical_trials'...")
    df = pd.read_sql("SELECT * FROM silver_clinical_trials", con=engine)

    if df.empty:
        raise RuntimeError(
            "Silver table is empty. Run Phase 4 (spark_silver.py) first."
        )

    logger.info(f"  Loaded {len(df)} records from Silver layer.")
    return df


def _build_dim_patient(df: pd.DataFrame) -> pd.DataFrame:
    """
    Step 2 — Build dim_patient dimension table.

    Logic:
      - Select patient_id, age, gender, country from Silver
      - Deduplicate: keep ONE record per patient_id (last seen wins — SCD Type 1)
      - Assign a sequential surrogate key (patient_key)
      - Truncate & reload dim_patient table

    Returns a DataFrame with [patient_key, patient_id] for FK lookup.
    """
    logger.info("Step 2: Building dim_patient...")

    dim = (
        df[["patient_id", "age", "gender", "country"]]
        .drop_duplicates(subset=["patient_id"], keep="last")
        .reset_index(drop=True)
    )
    dim.insert(0, "patient_key", range(1, len(dim) + 1))

    # Load into dim_patient
    dim[["patient_id", "age", "gender", "country"]].to_sql(
        name="dim_patient", con=engine, if_exists="append", index=False, chunksize=500
    )

    # Re-read to get DB-assigned surrogate keys
    dim_db = pd.read_sql(
        "SELECT patient_key, patient_id FROM dim_patient", con=engine
    )
    logger.info(f"  dim_patient: {len(dim_db)} unique patients loaded.")
    return dim_db


def _build_dim_trial(df: pd.DataFrame) -> pd.DataFrame:
    """
    Step 3 — Build dim_trial dimension table.

    Logic:
      - Select trial_id, treatment, start_date, end_date, treatment_duration_days
      - Deduplicate: one record per trial_id
      - Assign surrogate key (trial_key)
      - Truncate & reload

    Returns a DataFrame with [trial_key, trial_id] for FK lookup.
    """
    logger.info("Step 3: Building dim_trial...")

    dim = (
        df[["trial_id", "treatment", "start_date", "end_date", "treatment_duration_days"]]
        .drop_duplicates(subset=["trial_id"], keep="last")
        .reset_index(drop=True)
    )

    dim[["trial_id", "treatment", "start_date", "end_date", "treatment_duration_days"]].to_sql(
        name="dim_trial", con=engine, if_exists="append", index=False, chunksize=500
    )

    dim_db = pd.read_sql(
        "SELECT trial_key, trial_id FROM dim_trial", con=engine
    )
    logger.info(f"  dim_trial: {len(dim_db)} unique trials loaded.")
    return dim_db


def _build_dim_drug(df: pd.DataFrame) -> pd.DataFrame:
    """
    Step 4 — Build dim_drug dimension table.

    Logic:
      - Select unique drug_id values from Silver
      - Derive human-readable drug_name via catalog lookup
      - Assign surrogate key (drug_key)
      - Truncate & reload

    Returns a DataFrame with [drug_key, drug_id] for FK lookup.
    """
    logger.info("Step 4: Building dim_drug...")

    unique_drugs = (
        df[["drug_id"]]
        .drop_duplicates(subset=["drug_id"])
        .reset_index(drop=True)
    )
    unique_drugs["drug_name"] = unique_drugs["drug_id"].apply(_derive_drug_name)

    unique_drugs[["drug_id", "drug_name"]].to_sql(
        name="dim_drug", con=engine, if_exists="append", index=False, chunksize=500
    )

    dim_db = pd.read_sql(
        "SELECT drug_key, drug_id FROM dim_drug", con=engine
    )
    logger.info(f"  dim_drug: {len(dim_db)} unique drugs loaded.")
    return dim_db


def _build_fact_clinical_outcomes(
    df: pd.DataFrame,
    dim_patient: pd.DataFrame,
    dim_trial: pd.DataFrame,
    dim_drug: pd.DataFrame,
) -> int:
    """
    Step 5 — Build fact_clinical_outcomes central fact table.

    Logic:
      - Start from Silver records (one row per patient-trial event)
      - JOIN to each dimension to resolve surrogate FKs
      - Derive analytical columns: outcome_binary, outcome_category
      - Truncate & reload fact table
      - Return count of loaded fact rows
    """
    logger.info("Step 5: Building fact_clinical_outcomes...")

    fact = df[["patient_id", "trial_id", "drug_id", "dosage",
               "treatment_duration_days", "outcome"]].copy()

    # Derive analytical flags
    fact["outcome_binary"]   = fact["outcome"].apply(_derive_outcome_binary)
    fact["outcome_category"] = fact["outcome"].apply(_derive_outcome_category)

    # Resolve surrogate FKs via merge (equivalent to SQL JOIN)
    fact = fact.merge(dim_patient, on="patient_id", how="left")
    fact = fact.merge(dim_trial,   on="trial_id",   how="left")
    fact = fact.merge(dim_drug,    on="drug_id",    how="left")

    # Validate: no unresolved FKs (nulls in key columns = referential integrity violation)
    null_fks = fact[["patient_key", "trial_key", "drug_key"]].isnull().sum()
    if null_fks.any():
        logger.warning(f"  Referential integrity warnings — unresolved FKs:\n{null_fks}")

    # Select final fact columns in order
    fact_cols = [
        "patient_key", "trial_key", "drug_key",
        "patient_id", "trial_id", "drug_id",
        "dosage", "treatment_duration_days",
        "outcome", "outcome_binary", "outcome_category"
    ]
    fact_final = fact[fact_cols].copy()

    fact_final.to_sql(
        name="fact_clinical_outcomes", con=engine,
        if_exists="append", index=False, chunksize=500
    )

    count = len(fact_final)
    logger.info(f"  fact_clinical_outcomes: {count} fact rows loaded.")
    return count


def _export_gold_parquet(df_silver: pd.DataFrame, dim_patient: pd.DataFrame,
                          dim_trial: pd.DataFrame, dim_drug: pd.DataFrame) -> None:
    """
    Step 6 — Export Gold layer tables as Parquet files.

    Parquet exports allow downstream tools (Spark, Databricks, dbt, Power BI)
    to read Gold layer data without querying the database directly.
    Files are written under data/gold/.
    """
    logger.info("Step 6: Exporting Gold layer to Parquet data lake...")

    gold_dir = BASE_DIR / "data" / "gold"
    gold_dir.mkdir(parents=True, exist_ok=True)

    try:
        # Read full dimension tables from DB (includes surrogate keys)
        pd.read_sql("SELECT * FROM dim_patient", con=engine).to_parquet(
            gold_dir / "dim_patient.parquet", index=False, engine="pyarrow"
        )
        pd.read_sql("SELECT * FROM dim_trial", con=engine).to_parquet(
            gold_dir / "dim_trial.parquet", index=False, engine="pyarrow"
        )
        pd.read_sql("SELECT * FROM dim_drug", con=engine).to_parquet(
            gold_dir / "dim_drug.parquet", index=False, engine="pyarrow"
        )
        pd.read_sql("SELECT * FROM fact_clinical_outcomes", con=engine).to_parquet(
            gold_dir / "fact_clinical_outcomes.parquet", index=False, engine="pyarrow"
        )
        logger.info(f"  Gold Parquet files saved to: {gold_dir}")

    except Exception as e:
        logger.warning(f"  Parquet export skipped (pyarrow not available): {e}")
        # CSV fallback
        pd.read_sql("SELECT * FROM dim_patient",           con=engine).to_csv(gold_dir / "dim_patient.csv",           index=False)
        pd.read_sql("SELECT * FROM dim_trial",             con=engine).to_csv(gold_dir / "dim_trial.csv",             index=False)
        pd.read_sql("SELECT * FROM dim_drug",              con=engine).to_csv(gold_dir / "dim_drug.csv",              index=False)
        pd.read_sql("SELECT * FROM fact_clinical_outcomes", con=engine).to_csv(gold_dir / "fact_clinical_outcomes.csv", index=False)
        logger.info(f"  Gold CSV fallback files saved to: {gold_dir}")


def _print_gold_summary() -> None:
    """
    Step 7 — Print a Gold Layer analytics summary report.

    Demonstrates the power of the star schema by running simple aggregate
    queries against the fact and dimension tables.
    """
    logger.info("Step 7: Running Gold Layer analytics summary...")
    print("\n" + "=" * 65)
    print("  GOLD LAYER - ANALYTICAL SUMMARY REPORT")
    print("=" * 65)

    queries = {
        "Total Fact Records"      : "SELECT COUNT(*) FROM fact_clinical_outcomes",
        "Unique Patients"         : "SELECT COUNT(*) FROM dim_patient",
        "Unique Trials"           : "SELECT COUNT(*) FROM dim_trial",
        "Unique Drugs"            : "SELECT COUNT(*) FROM dim_drug",
        "Overall Positive Outcome Rate (%)": (
            "SELECT ROUND((AVG(outcome_binary) * 100)::NUMERIC, 2) "
            "FROM fact_clinical_outcomes"
        ),
        "Avg Treatment Duration (days)": (
            "SELECT ROUND(AVG(treatment_duration_days)::NUMERIC, 1) "
            "FROM fact_clinical_outcomes "
            "WHERE treatment_duration_days IS NOT NULL"
        ),
    }

    for label, sql in queries.items():
        result = pd.read_sql(sql, con=engine).iloc[0, 0]
        print(f"  {label:<40}: {result}")

    print("\n  -- Outcome Breakdown by Category --")
    outcome_summary = pd.read_sql(
        "SELECT outcome_category, COUNT(*) as count, "
        "ROUND(AVG(dosage)::NUMERIC, 2) as avg_dosage_mg "
        "FROM fact_clinical_outcomes "
        "GROUP BY outcome_category "
        "ORDER BY count DESC",
        con=engine
    )
    print(outcome_summary.to_string(index=False))

    print("\n  -- Top 5 Countries by Patient Count --")
    country_summary = pd.read_sql(
        "SELECT p.country, COUNT(*) as patient_count "
        "FROM fact_clinical_outcomes f "
        "JOIN dim_patient p ON f.patient_key = p.patient_key "
        "GROUP BY p.country "
        "ORDER BY patient_count DESC "
        "LIMIT 5",
        con=engine
    )
    print(country_summary.to_string(index=False))

    print("\n  -- Treatment Success Rate by Drug --")
    drug_summary = pd.read_sql(
        "SELECT d.drug_name, "
        "COUNT(*) as total_trials, "
        "SUM(f.outcome_binary) as positive_outcomes, "
        "ROUND((AVG(f.outcome_binary) * 100)::NUMERIC, 1) as success_rate_pct "
        "FROM fact_clinical_outcomes f "
        "JOIN dim_drug d ON f.drug_key = d.drug_key "
        "GROUP BY d.drug_name "
        "ORDER BY success_rate_pct DESC",
        con=engine
    )
    print(drug_summary.to_string(index=False))
    print("=" * 65 + "\n")


