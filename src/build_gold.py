def _derive_outcome_binary(outcome: str) -> int:
    """
    Map raw outcome string to binary flag.
    Positive outcomes (patient improved / completed) → 1
    Negative / Neutral outcomes → 0
    """
    positive_keywords = {"recovered", "improved", "remission", "stable",
                         "completed", "effective"}
    return 1 if str(outcome).strip().lower() in positive_keywords else 0


def _derive_outcome_category(outcome: str) -> str:
    """
    Map raw outcome string to 3-tier analytical category.
    """
    outcome_lower = str(outcome).strip().lower()
    positive = {"recovered", "improved", "remission", "completed", "effective"}
    negative = {"worsened", "deceased", "adverse reaction", "withdrawn",
                "adverse event", "non-responsive"}
    neutral  = {"stable", "no change"}

    if outcome_lower in positive:
        return "Positive"
    elif outcome_lower in negative:
        return "Negative"
    elif outcome_lower in neutral:
        return "Neutral"
    else:
        return "Neutral"


def _derive_drug_name(drug_id: str) -> str:
    """
    Generate a human-readable drug name from drug_id.
    Catalog matches the DRUG-1..DRUG-4 IDs generated by generate_synthetic_data.py.
    """
    drug_catalog = {
        "DRUG-1": "Investigational Drug Alpha",
        "DRUG-2": "Investigational Drug Beta",
        "DRUG-3": "Investigational Drug Gamma",
        "DRUG-4": "Investigational Drug Delta",
        # Legacy D-00x format fallback
        "D-001": "Investigational Drug Alpha",
        "D-002": "Investigational Drug Beta",
        "D-003": "Investigational Drug Gamma",
        "D-004": "Investigational Drug Delta",
        "D-005": "Investigational Drug Epsilon",
    }
    return drug_catalog.get(str(drug_id).strip(), f"Drug {drug_id}")


