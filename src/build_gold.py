def build_gold_layer() -> int:
    """
    Phase 5 Orchestrator — runs all Gold layer build steps in sequence.

    Steps:
      1. Load Silver data
      2. Build dim_patient
      3. Build dim_trial
      4. Build dim_drug
      5. Build fact_clinical_outcomes (with FK resolution + derived metrics)
      6. Export Gold Parquet data lake
      7. Print analytics summary report

    Returns the total number of fact rows loaded.
    """
    logger.info("=" * 60)
    logger.info("  Starting Phase 5: Gold Layer - Star Schema Build")
    logger.info("=" * 60)

    # Ensure all Gold table schemas exist in the database
    Base.metadata.create_all(bind=engine)

    # Truncate all Gold tables in FK-safe order:
    # fact table must be cleared BEFORE dimension tables it references
    from sqlalchemy import text as sa_text
    with engine.connect() as conn:
        conn.execute(sa_text("DELETE FROM fact_clinical_outcomes"))
        conn.execute(sa_text("DELETE FROM dim_patient"))
        conn.execute(sa_text("DELETE FROM dim_trial"))
        conn.execute(sa_text("DELETE FROM dim_drug"))
        conn.commit()
    logger.info("Gold tables cleared (FK-safe truncation order: fact -> dims).")

    # Run pipeline steps
    df_silver   = _load_silver_data()
    dim_patient = _build_dim_patient(df_silver)
    dim_trial   = _build_dim_trial(df_silver)
    dim_drug    = _build_dim_drug(df_silver)
    fact_count  = _build_fact_clinical_outcomes(df_silver, dim_patient, dim_trial, dim_drug)

    _export_gold_parquet(df_silver, dim_patient, dim_trial, dim_drug)
    _print_gold_summary()

    logger.info(f"Phase 5 Complete — Gold Layer built with {fact_count} fact rows.")
    return fact_count


if __name__ == "__main__":
    count = build_gold_layer()
    print(f"\n--- Phase 5 Complete: Gold Layer = {count} fact records ---")
